import { cp, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { applyIntent, initProject, listIntents, loadProject } from "@osl/core";
import { drizzleNextBackend } from "../src/index.js";

const FIXTURES = path.resolve(__dirname, "../../../fixtures");

async function irFor(fixture: string) {
  const root = await mkdtemp(path.join(tmpdir(), "osl-det-"));
  await initProject(root, { name: fixture, backend: "drizzle-next" });
  await cp(path.join(FIXTURES, fixture, "intents"), path.join(root, ".osl/intents"), { recursive: true });
  for (const id of await listIntents(root)) await applyIntent(root, id);
  const project = await loadProject(root);
  await rm(root, { recursive: true, force: true });
  return project;
}

describe("drizzle-next backend", () => {
  for (const fixture of ["blog", "todo"]) {
    it(`generates ${fixture} deterministically`, async () => {
      const project = await irFor(fixture);
      const input = { ir: project.ir, revisions: project.lock.revisions, config: project.config };
      const a = drizzleNextBackend.generate(input);
      const b = drizzleNextBackend.generate(input);
      expect(a).toEqual(b);
      expect(a.map(f => f.path)).toEqual([...a.map(f => f.path)].sort((x, y) => x.localeCompare(y)));
      const generated = a.filter(f => (f.mode ?? "generated") === "generated");
      expect(generated.every(f => f.content.includes("Generated by OSL") || /\.(sql|md|json)$/.test(f.path))).toBe(
        true
      );
      expect(a.filter(f => f.mode === "scaffold").map(f => f.path)).toContain(
        "src/extensions/posts.ts".replace("posts", fixture === "blog" ? "posts" : "tasks")
      );
    });
  }

  it("never emits a hidden column in presenters or validation", async () => {
    const project = await irFor("blog");
    const files = drizzleNextBackend.generate({
      ir: project.ir,
      revisions: project.lock.revisions,
      config: project.config
    });
    const present = files.find(f => f.path === "generated/present.ts")!.content;
    expect(present).not.toMatch(/password_hash: row/);
    const validation = files.find(f => f.path === "generated/validation.ts")!.content;
    expect(validation).not.toContain("password_hash");
  });

  it("installs with the configured package manager", async () => {
    const project = await irFor("todo");
    const withPm = (pm?: string) => ({
      ...project.config,
      backend_options: pm ? { package_manager: pm } : {}
    });
    expect(drizzleNextBackend.runtime(withPm()).install[0].command).toBe("pnpm");
    expect(drizzleNextBackend.runtime(withPm("bun")).install[0].command).toBe("bun");
    expect(drizzleNextBackend.runtime(withPm("npm")).install[0].command).toBe("npm");
    expect(() =>
      drizzleNextBackend.generate({ ir: project.ir, revisions: project.lock.revisions, config: withPm("yarn") })
    ).toThrow(/package_manager/);
  });
});
