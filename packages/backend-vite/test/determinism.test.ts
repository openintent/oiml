import { cp, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { applyIntent, initProject, listIntents, loadProject } from "@osl/core";
import { honoTrpcViteBackend } from "../src/index.js";

const FIXTURES = path.resolve(__dirname, "../../../fixtures");

async function projectFor(fixture: string) {
  const root = await mkdtemp(path.join(tmpdir(), "osl-det-"));
  await initProject(root, { name: fixture, backend: honoTrpcViteBackend.name });
  await cp(path.join(FIXTURES, fixture, "intents"), path.join(root, ".osl/intents"), { recursive: true });
  for (const id of await listIntents(root)) await applyIntent(root, id);
  const project = await loadProject(root);
  await rm(root, { recursive: true, force: true });
  return project;
}

describe("hono-trpc-vite backend", () => {
  for (const fixture of ["blog", "todo"]) {
    it(`generates ${fixture} deterministically`, async () => {
      const project = await projectFor(fixture);
      const input = { ir: project.ir, revisions: project.lock.revisions, config: project.config };
      const a = honoTrpcViteBackend.generate(input);
      const b = honoTrpcViteBackend.generate(input);
      expect(a).toEqual(b);
      expect(a.map(f => f.path)).toEqual([...a.map(f => f.path)].sort((x, y) => x.localeCompare(y)));
      const generated = a.filter(f => (f.mode ?? "generated") === "generated");
      expect(generated.every(f => f.content.includes("Generated by OSL") || /\.(sql|md|json)$/.test(f.path))).toBe(
        true
      );
    });
  }

  it("renders the blog sidebar, pages and routes", async () => {
    const project = await projectFor("blog");
    const files = honoTrpcViteBackend.generate({
      ir: project.ir,
      revisions: project.lock.revisions,
      config: project.config
    });
    const paths = files.map(f => f.path);
    expect(paths).toContain("generated/app/nav.ts");
    expect(paths).toContain("generated/app/pages/posts.tsx");
    expect(paths).toContain("src/routes/posts.tsx");
    expect(paths).toContain("src/routes/posts.$id.tsx");
    expect(paths).toContain("src/routes/posts.new.tsx");
    expect(paths).toContain("src/routes/about.tsx");
    expect(paths).toContain("src/components/app-sidebar.tsx");
    const nav = files.find(f => f.path === "generated/app/nav.ts")!.content;
    expect(nav).toContain(
      'import { Archive, FileText, House, Info, Kanban, Megaphone, PenLine, Shield, Users } from "lucide-react";'
    );
    expect(nav).toContain("footer: { user: true, settings: true }");
    // the identity page has no create, so no "new" route
    expect(paths).not.toContain("src/routes/users.new.tsx");
    const present = files.find(f => f.path === "generated/present.ts")!.content;
    expect(present).not.toMatch(/password_hash: row/);
  });

  it("presents a row to a viewer where a field has a read rule, and tells the session its fields", async () => {
    const project = await projectFor("blog");
    const files = honoTrpcViteBackend.generate({
      ir: project.ir,
      revisions: project.lock.revisions,
      config: project.config
    });
    const file = (name: string) => files.find(f => f.path === name)!.content;
    const present = file("generated/present.ts");
    expect(present).toContain('import { memberTenantIds, verdict, type Rule } from "./server/access";');
    expect(present).toContain("export function presentArticle(row: schema.Article, viewer: Viewer): PublicArticle {");
    for (const f of files.filter(f => /generated\/.*\.ts$/.test(f.path))) {
      expect(f.content, f.path).not.toMatch(/present(Article|User)\(\w+(\.\w+)*\)/);
      expect(f.content, f.path).not.toMatch(/\.map\(present(Article|User)\)/);
    }
    const posts = file("generated/server/resources/posts.ts");
    expect(posts).toContain("return presentArticle(row, ctx.session);");
    expect(posts).toContain('await emit("Article.created", presentArticle(row, SERVER));');
    expect(posts).toContain("data: rows.map(row => presentListRow(row, ctx.session))");
    const auth = file("generated/server/auth.ts");
    expect(auth).toContain("return shownUser(ctx.session);");
    expect(auth).toContain(
      "{ user: shownUser(ctx.session), memberships: ctx.session.memberships, fields: visibleFields(ctx.session) }"
    );
    expect(file("generated/app/client.ts")).toContain("export function fieldsOf(session: Session | undefined)");
  });

  it("installs and runs the project with the configured package manager", async () => {
    const project = await projectFor("todo");
    const withPm = (pm?: string) => ({
      ...project.config,
      backend_options: pm ? { ...project.config.backend_options, package_manager: pm } : project.config.backend_options
    });
    const generated = (pm?: string) =>
      honoTrpcViteBackend.generate({ ir: project.ir, revisions: project.lock.revisions, config: withPm(pm) });
    const packageJson = (pm?: string) => JSON.parse(generated(pm).find(f => f.path === "package.json")!.content);
    const readme = (pm?: string) => generated(pm).find(f => f.path === "generated/README.md")!.content;

    expect(honoTrpcViteBackend.runtime(withPm()).install[0].command).toBe("pnpm");
    expect(packageJson().pnpm).toBeUndefined();
    const settings = generated().find(f => f.path === "pnpm-workspace.yaml");
    expect(settings?.mode).toBe("scaffold");
    expect(settings?.content).toContain("esbuild: true");
    expect(generated("bun").some(f => f.path === "pnpm-workspace.yaml")).toBe(false);
    expect(packageJson().scripts.dev).toBe("node scripts/dev.mjs");
    expect(readme()).toContain("`pnpm dev`");

    expect(honoTrpcViteBackend.runtime(withPm("bun")).install[0]).toEqual({ command: "bun", args: ["install"] });
    expect(packageJson("bun")).toMatchObject({ trustedDependencies: ["esbuild"] });
    expect(packageJson("bun").pnpm).toBeUndefined();
    expect(readme("bun")).toContain("`bun run dev`");

    expect(honoTrpcViteBackend.runtime(withPm("npm")).install[0].command).toBe("npm");
    expect(packageJson("npm").pnpm).toBeUndefined();
    expect(packageJson("npm").trustedDependencies).toBeUndefined();
    expect(readme("npm")).toContain("`npm run dev`");

    expect(() => generated("yarn")).toThrow(/package_manager/);
    expect(() => honoTrpcViteBackend.runtime(withPm("yarn"))).toThrow(/package_manager/);
    expect(generated().some(f => f.path === "scripts/dev.mjs" && f.mode === "scaffold")).toBe(true);
  });
});
