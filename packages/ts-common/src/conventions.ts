import type { ColumnIR, EntityIR, IR } from "@osl/core";
import { toCamelCase, toPascalCase } from "@osl/core";

/**
 * What differs between the TypeScript backends when they emit the same code:
 * the file headers (which name the backend) and how generated code imports
 * user-owned files and vice versa. Everything a shared generator writes goes
 * through one of these, so each backend's output stays its own.
 */
export interface TsConventions {
  /** Header of a file OSL rewrites on every generate */
  header(what: string): string;
  /** Header of a file OSL writes once and the user owns */
  scaffoldHeader(what: string): string;
  /** Import specifier for a path under the user's src directory, e.g. src("events/x") */
  src(path: string): string;
  /** Import specifier for a path under the generated directory, e.g. generated("db/schema") */
  generated(path: string): string;
}

export function conventions(pkg: string, aliases: { src: string; generated: string }): TsConventions {
  return {
    header: what =>
      `// Generated by OSL (${pkg}). ${what}\n// Do not edit: this file is rewritten on every osl generate.\n`,
    scaffoldHeader: what => `// Created once by OSL (${pkg}). ${what}\n// You own this file: OSL never rewrites it.\n`,
    src: path => `${aliases.src}/${path}`,
    generated: path => `${aliases.generated}/${path}`
  };
}

/** JSON string literal for generated code */
export const q = (value: string): string => JSON.stringify(value);

export function tableExport(entity: EntityIR): string {
  return toCamelCase(entity.table);
}

export function typeName(entity: EntityIR): string {
  return toPascalCase(entity.name);
}

export function enumExport(name: string): string {
  return `${toCamelCase(name)}Enum`;
}

export function relationsExport(entity: EntityIR): string {
  return `${tableExport(entity)}Relations`;
}

export function entityByName(ir: IR, name: string): EntityIR {
  const entity = ir.entities.find(e => e.name === name);
  if (!entity) throw new Error(`entity ${name} missing from IR`);
  return entity;
}

export function column(entity: EntityIR, name: string): ColumnIR {
  const col = entity.columns.find(c => c.name === name);
  if (!col) throw new Error(`column ${entity.name}.${name} missing from IR`);
  return col;
}

export function singlePrimaryKey(entity: EntityIR): ColumnIR {
  if (entity.primaryKey.length !== 1)
    throw new Error(`resource entity ${entity.name} needs a single-column primary key`);
  return column(entity, entity.primaryKey[0]);
}

export function isBytes(column: ColumnIR): boolean {
  return column.type.kind === "scalar" && column.type.scalar === "bytes";
}

export function cap(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function indent(text: string, spaces: number): string {
  const pad = " ".repeat(spaces);
  return text
    .split("\n")
    .map(line => (line.length ? pad + line : line))
    .join("\n");
}
