import { spawnSync } from "node:child_process";
import { cp, mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { applyIntent, initProject, listIntents, loadProject } from "@osl/core";
import { ginPgxBackend } from "../src/index.js";

const FIXTURES = path.resolve(__dirname, "../../../fixtures");

async function irFor(fixture: string) {
  const root = await mkdtemp(path.join(tmpdir(), "osl-det-"));
  await initProject(root, { name: fixture, backend: "gin-pgx" });
  await cp(path.join(FIXTURES, fixture, "intents"), path.join(root, ".osl/intents"), { recursive: true });
  for (const id of await listIntents(root)) await applyIntent(root, id);
  const project = await loadProject(root);
  await rm(root, { recursive: true, force: true });
  return project;
}

const hasGofmt = spawnSync("gofmt", ["-h"]).error === undefined;

describe("gin-pgx backend", () => {
  const hooksOf: Record<string, string> = { blog: "posts", todo: "tasks", workspace: "teams" };
  for (const fixture of ["blog", "todo", "workspace"]) {
    it(`generates ${fixture} deterministically`, async () => {
      const project = await irFor(fixture);
      const input = { ir: project.ir, revisions: project.lock.revisions, config: project.config };
      const a = ginPgxBackend.generate(input);
      const b = ginPgxBackend.generate(input);
      expect(a).toEqual(b);
      expect(a.map(f => f.path)).toEqual([...a.map(f => f.path)].sort((x, y) => x.localeCompare(y)));
      const generated = a.filter(f => (f.mode ?? "generated") === "generated");
      expect(
        generated.every(
          f =>
            f.content.includes("Generated by OSL") ||
            f.path.endsWith(".sql") ||
            f.path.endsWith(".md") ||
            f.path.endsWith(".json")
        )
      ).toBe(true);
      expect(a.filter(f => f.mode === "scaffold").map(f => f.path)).toContain(
        `src/extensions/${hooksOf[fixture]}/hooks.go`
      );
      expect(a.map(f => f.path)).not.toContain("go.sum");
      expect(a.map(f => f.path)).toContain("generated/openapi.json");
      expect(a.map(f => f.path)).toContain("cmd/seed/main.go");
    });

    it(`writes gofmt-clean Go for ${fixture}`, async context => {
      if (!hasGofmt) context.skip();
      const project = await irFor(fixture);
      const files = ginPgxBackend.generate({
        ir: project.ir,
        revisions: project.lock.revisions,
        config: project.config
      });
      const root = await mkdtemp(path.join(tmpdir(), "osl-gofmt-"));
      for (const file of files.filter(f => f.path.endsWith(".go"))) {
        await mkdir(path.dirname(path.join(root, file.path)), { recursive: true });
        await writeFile(path.join(root, file.path), file.content);
      }
      const result = spawnSync("gofmt", ["-l", "."], { cwd: root, encoding: "utf8" });
      await rm(root, { recursive: true, force: true });
      expect(result.stderr).toBe("");
      expect(result.stdout.trim()).toBe("");
    });
  }

  it("generates actions, files, providers and jobs for blog", async () => {
    const project = await irFor("blog");
    const files = ginPgxBackend.generate({ ir: project.ir, revisions: project.lock.revisions, config: project.config });
    const paths = files.map(f => f.path);
    expect(paths).toContain("generated/actions/actions.go");
    expect(paths).toContain("generated/actions/handlers/handlers.go");
    expect(files.find(f => f.path === "src/actions/posts_publish/handler.go")?.mode).toBe("scaffold");
    expect(paths).toContain("generated/files/files.go");
    expect(paths).toContain("generated/storage/storage.go");
    expect(paths).toContain("generated/auth/providers.go");
    expect(paths).toContain("generated/jobs/jobs.go");
    expect(files.find(f => f.path === "cmd/worker/main.go")?.mode).toBe("scaffold");
    expect(files.find(f => f.path === "docker-compose.yml")?.content).toContain("OSL_ROLE: worker");
    expect(paths.filter(p => p.startsWith("generated/tests/"))).toEqual([
      "generated/tests/01_register_and_sign_in_test.go",
      "generated/tests/02_alice_writes_a_post_test.go",
      "generated/tests/03_post_validation_test.go",
      "generated/tests/04_tagged_articles_test.go",
      "generated/tests/05_publishing_test.go",
      "generated/tests/06_cover_images_test.go",
      "generated/tests/07_search_and_sort_test.go",
      "generated/tests/08_magic_link_test.go",
      "generated/tests/09_comments_and_moderation_test.go",
      "generated/tests/10_banning_test.go",
      "generated/tests/11_scheduled_publishing_test.go",
      "generated/tests/support_test.go"
    ]);
    const runtime = ginPgxBackend.runtime(project.config);
    expect(runtime.ignoredTables).toEqual(["river_%"]);
    expect(runtime.seed("http://localhost:1").env).toEqual({ OSL_BASE_URL: "http://localhost:1" });
  });

  it("generates member rules and the creator membership for workspace", async () => {
    const project = await irFor("workspace");
    const files = ginPgxBackend.generate({ ir: project.ir, revisions: project.lock.revisions, config: project.config });
    const teams = files.find(f => f.path === "generated/resources/teams.go")!.content;
    expect(teams).toContain('access.Rule{Kind: "member", Field: "id", Role: "admin"}');
    expect(teams).toContain("h.db.Begin(ctx)");
    expect(teams).toContain('"owner"');
    const access = files.find(f => f.path === "generated/access/access.go")!.content;
    expect(access).toContain("MemberTenantIDs");
  });

  it("never emits a hidden column in public shapes or validation", async () => {
    const project = await irFor("blog");
    const files = ginPgxBackend.generate({ ir: project.ir, revisions: project.lock.revisions, config: project.config });
    const entities = files.find(f => f.path === "generated/models/entities.go")!.content;
    const publicUser = entities.slice(entities.indexOf("type PublicUser struct"), entities.indexOf("// ScanUser"));
    expect(publicUser).not.toContain("password_hash");
    expect(entities).toMatch(/PasswordHash \*string\s+`json:"-"`/);
    const validation = files.find(f => f.path === "generated/validation/resources.go")!.content;
    expect(validation).not.toContain("password_hash");
  });
});
