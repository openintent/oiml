import type { GeneratedFile, IR } from "@osl/core";
import { REGION_BEGIN, REGION_END, SEAL_KEY_ENV, SEAL_KEY_HINT, hasSealed } from "@osl/core";
import { hasProviders, oauthProviders } from "./auth.js";
import { sealReadme } from "./seal.js";

export const GO_VERSION = "1.26";

export const DEPENDENCIES: Record<string, string> = {
  "github.com/gin-gonic/gin": "v1.10.1",
  "github.com/jackc/pgx/v5": "v5.7.5",
  "golang.org/x/crypto": "v0.58.0"
};

/** Added when the model has file fields: S3 through the AWS SDK */
export const STORAGE_DEPENDENCIES: Record<string, string> = {
  "github.com/aws/aws-sdk-go-v2": "v1.47.7",
  "github.com/aws/aws-sdk-go-v2/config": "v1.33.15",
  "github.com/aws/aws-sdk-go-v2/credentials": "v1.20.15",
  "github.com/aws/aws-sdk-go-v2/service/s3": "v1.114.8"
};

/** Added when the model queues events: River on the same database */
export const JOBS_DEPENDENCIES: Record<string, string> = {
  "github.com/riverqueue/river": "v0.51.0",
  "github.com/riverqueue/river/riverdriver/riverpgxv5": "v0.51.0",
  "github.com/robfig/cron/v3": "v3.0.1"
};

const PORT = 8080;

export function scaffoldFiles(ir: IR, modulePath: string): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  const dependencies = {
    ...DEPENDENCIES,
    ...(ir.files ? STORAGE_DEPENDENCIES : {}),
    ...(ir.jobs ? JOBS_DEPENDENCIES : {})
  };

  files.push({
    path: "go.mod",
    mode: "scaffold",
    content: `module ${modulePath}

go ${GO_VERSION}

require (
${Object.entries(dependencies)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, version]) => `\t${name} ${version}`)
  .join("\n")}
)
`
  });

  files.push({
    path: ".gitignore",
    mode: "scaffold",
    content: `.env
*.test
/bin/
/storage/
`
  });

  const env: string[] = [`DATABASE_URL=postgres://postgres@localhost:5432/${ir.name}`, `PORT=${PORT}`];
  const isolation = ir.auth?.tenancy?.isolation;
  if (isolation)
    env.splice(
      1,
      0,
      "# The web process connects as the role the tenant policies bind; osl migrate gives it the password you put here",
      `DATABASE_APP_URL=postgres://${isolation.appRole}:CHOOSE-A-PASSWORD@localhost:5432/${ir.name}`
    );
  if (ir.auth) env.push("OSL_SESSION_SECRET=change-me-to-a-long-random-string");
  if (hasSealed(ir))
    env.push(
      `# The key sealed fields are encrypted under (${SEAL_KEY_HINT}). Keep it: without it the stored values cannot be read`,
      `${SEAL_KEY_ENV}=`
    );
  if (hasProviders(ir)) env.push(`OSL_APP_URL=http://localhost:${PORT}`);
  if (ir.auth?.providers.some(p => p.kind === "magic_link"))
    env.push(
      "# OSL_EMAIL=log|resend|capture (resend when RESEND_API_KEY is set, else log)",
      "# RESEND_API_KEY=",
      "# EMAIL_FROM=no-reply@example.com"
    );
  for (const p of oauthProviders(ir)) {
    const name = p.name.toUpperCase().replace(/-/g, "_");
    env.push(`OAUTH_${name}_CLIENT_ID=`, `OAUTH_${name}_CLIENT_SECRET=`);
  }
  if (ir.files)
    env.push(
      "# OSL_STORAGE=local|s3 (s3 when S3_BUCKET is set, else local); OSL_STORAGE_DIR=./storage for local",
      "# S3_BUCKET=",
      "# S3_REGION=us-east-1",
      "# S3_ENDPOINT=",
      "# S3_ACCESS_KEY_ID=",
      "# S3_SECRET_ACCESS_KEY=",
      "# S3_FORCE_PATH_STYLE=false"
    );
  if (ir.jobs) env.push("# OSL_ROLE=web|worker|all (default all: this process also runs queued events)");
  files.push({
    path: ".env.example",
    mode: "regions",
    content: `# Copy to .env and export it, or set the variables in the environment. Keep your own variables outside the OSL region.
${REGION_BEGIN("env", "#")}
${env.join("\n")}
${REGION_END("env", "#")}
`
  });

  files.push({
    path: "generated/README.md",
    content: `# Generated by OSL

Everything in this directory is rewritten by \`osl generate\` from \`.osl/model.yaml\`. Do not edit it.

Put your own code in \`src/\`: \`src/extensions/<resource>/hooks.go\` holds hooks around each resource's handlers, \`src/actions/<handler>/handler.go\` holds the body of each action and \`src/events/<handler>/handler.go\` holds event handlers. OSL creates those files once and never touches them again. \`cmd/server/main.go\`, \`cmd/worker/main.go\`, \`go.mod\`, the Dockerfile and docker-compose.yml are created once as well.

Run \`go mod tidy\` after generating, then \`go run ./cmd/server\` with \`DATABASE_URL\` set. The contract tests under \`tests\` run with \`OSL_BASE_URL=http://localhost:${PORT} go test ./...\` against a running server; \`go run ./cmd/seed\` replays the model's seed steps against it. The REST contract is \`openapi.json\`, served at \`/api/openapi.json\`.

Migrations in \`db/migrations\` are a pure function of the model history. Apply them with \`osl migrate\`.
${
  isolation
    ? `
## Tenant isolation in the database

The model says \`auth.tenancy.isolation: database\`, so every tenant table has row-level security behind the rules. Two roles connect:

- \`DATABASE_URL\` is the owner: it runs the migrations and the worker's jobs (River), and the policies do not bind it.
- \`DATABASE_APP_URL\` is \`${isolation.appRole}\`, the role every request reads and writes as. A request sees the rows of the teams its caller belongs to, what a public read rule opens to everyone, and nothing else; outside a request it sees no tenant row at all. \`app.New\` refuses to build the engine if this URL connects as the owner, a superuser or a role with BYPASSRLS.

The migrations create \`${isolation.appRole}\` without a login and without a password. Put \`DATABASE_APP_URL=postgres://${isolation.appRole}:<a password you choose>@host:5432/${ir.name}\` in the environment and run \`osl migrate\`: it gives the role that password. No password is in any generated file.

Handlers and your own code hold the database as a \`*db.Scope\`: its \`Query\`, \`QueryRow\`, \`Exec\` and \`Begin\` are the pool's, and each statement runs with the tenants of its context bound for its own transaction (pass the request's context, \`ctx.Context()\` in an action). A schedule or timer gets the owner's pool behind the same type.
`
    : ""
}${sealReadme(ir, modulePath)}`
  });

  files.push(...dockerFiles(ir));
  return files;
}

/** Dockerfile, .dockerignore and docker-compose.yml: scaffolds the user owns. */
function dockerFiles(ir: IR): GeneratedFile[] {
  const binaries = ["server", ...(ir.jobs ? ["worker"] : []), "seed"];
  const dockerfile = `# Built by OSL once; yours to change. Two stages: build static binaries, run them on a minimal image.
FROM golang:${GO_VERSION}-alpine AS build
WORKDIR /app
COPY . .
RUN go mod tidy
${binaries.map(b => `RUN CGO_ENABLED=0 go build -o /out/${b} ./cmd/${b}`).join("\n")}

FROM gcr.io/distroless/static-debian12
WORKDIR /app
ENV PORT=${PORT}
COPY --from=build /out/ /app/
EXPOSE ${PORT}
CMD ["/app/server"]
`;
  // isolation: database: requests connect as the app role; its password comes from the environment (osl migrate set it), never from this file
  const isolation = ir.auth?.tenancy?.isolation;
  const appUrl = isolation
    ? `\n      DATABASE_APP_URL: postgres://${isolation.appRole}:\${OSL_APP_DB_PASSWORD:?set OSL_APP_DB_PASSWORD to the password osl migrate gave ${isolation.appRole}}@postgres:5432/${ir.name}`
    : "";
  // Sealed fields: the key comes from the environment and is required; no file carries one
  const sealKey = hasSealed(ir)
    ? `\n      ${SEAL_KEY_ENV}: \${${SEAL_KEY_ENV}:?set ${SEAL_KEY_ENV} to the key sealed fields are encrypted under (${SEAL_KEY_HINT})}`
    : "";
  const worker = ir.jobs
    ? `
  worker:
    build: .
    command: ["/app/worker"]
    environment:
      DATABASE_URL: postgres://postgres:postgres@postgres:5432/${ir.name}${sealKey}
      OSL_ROLE: worker
    depends_on:
      postgres:
        condition: service_healthy
`
    : "";
  const compose = `# Built by OSL once; yours to change. Run with: docker compose up --build
services:
  postgres:
    image: postgres:18
    environment:
      POSTGRES_USER: postgres
      POSTGRES_PASSWORD: postgres
      POSTGRES_DB: ${ir.name}
    ports:
      - "127.0.0.1:5432:5432"
    volumes:
      # The 18 image keeps its data under /var/lib/postgresql/18/docker, so the volume is its parent
      - pgdata:/var/lib/postgresql
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U postgres -d ${ir.name}"]
      interval: 2s
      timeout: 5s
      retries: 30

  app:
    build: .
    ports:
      - "${PORT}:${PORT}"
    environment:
      DATABASE_URL: postgres://postgres:postgres@postgres:5432/${ir.name}${appUrl}${sealKey}
      OSL_SESSION_SECRET: change-me-to-a-long-random-string
      OSL_APP_URL: http://localhost:${PORT}${ir.jobs ? "\n      OSL_ROLE: all" : ""}
    depends_on:
      postgres:
        condition: service_healthy
${worker}
volumes:
  pgdata:
`;
  return [
    { path: "Dockerfile", mode: "scaffold", content: dockerfile },
    { path: ".dockerignore", mode: "scaffold", content: ".env\n.git\n*.test\n/bin/\n/storage/\n" },
    { path: "docker-compose.yml", mode: "scaffold", content: compose }
  ];
}
