import type { ColumnIR, EntityIR, IR, RelationIR, RuleIR, Scalar } from "@osl/core";
import { conditionKey, ruleKey, toPascalCase } from "@osl/core";

/** Go string literal. JSON escapes are a subset of Go's interpreted string escapes. */
export const q = (value: string): string => JSON.stringify(value);

/** Go raw string literal; falls back to an interpreted literal when the text holds a backtick. */
export const raw = (value: string): string => (value.includes("`") ? q(value) : "`" + value + "`");

export const HEADER = (what: string) =>
  `// Generated by OSL (@osl/backend-gin-pgx). ${what}\n// Do not edit: this file is rewritten on every osl generate.\n`;

export const SCAFFOLD_HEADER = (what: string) =>
  `// Created once by OSL (@osl/backend-gin-pgx). ${what}\n// You own this file: OSL never rewrites it.\n`;

const INITIALISMS = new Set([
  "id",
  "ip",
  "ui",
  "db",
  "api",
  "url",
  "uri",
  "sql",
  "json",
  "html",
  "http",
  "https",
  "uuid",
  "xml",
  "css"
]);

/** Exported Go identifier for a snake_case name: author_id becomes AuthorID. */
export function exported(name: string): string {
  return name
    .split(/[_\-\s]+/)
    .filter(Boolean)
    .map(part =>
      INITIALISMS.has(part.toLowerCase()) ? part.toUpperCase() : part.charAt(0).toUpperCase() + part.slice(1)
    )
    .join("");
}

/** Unexported Go identifier: author_id becomes authorID. */
export function local(name: string): string {
  const e = exported(name);
  const firstWord = name.split(/[_\-\s]+/).filter(Boolean)[0] ?? "";
  if (INITIALISMS.has(firstWord.toLowerCase())) return firstWord.toLowerCase() + e.slice(firstWord.length);
  return e.charAt(0).toLowerCase() + e.slice(1);
}

/** Go package name for a directory: underscores and dashes removed. */
export function packageName(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]/g, "");
}

export function typeName(entity: EntityIR): string {
  return toPascalCase(entity.name);
}

export function entityByName(ir: IR, name: string): EntityIR {
  const entity = ir.entities.find(e => e.name === name);
  if (!entity) throw new Error(`entity ${name} missing from IR`);
  return entity;
}

export function column(entity: EntityIR, name: string): ColumnIR {
  const col = entity.columns.find(c => c.name === name);
  if (!col) throw new Error(`column ${entity.name}.${name} missing from IR`);
  return col;
}

export function relation(entity: EntityIR, name: string): RelationIR {
  const rel = entity.relations.find(r => r.name === name);
  if (!rel) throw new Error(`relation ${entity.name}.${name} missing from IR`);
  return rel;
}

export function singlePrimaryKey(entity: EntityIR): ColumnIR {
  if (entity.primaryKey.length !== 1)
    throw new Error(`resource entity ${entity.name} needs a single-column primary key`);
  return column(entity, entity.primaryKey[0]);
}

export function isBytes(col: ColumnIR): boolean {
  return col.type.kind === "scalar" && col.type.scalar === "bytes";
}

/** Columns that cross the HTTP API */
export function publicColumns(entity: EntityIR): ColumnIR[] {
  return entity.columns.filter(c => !c.hidden && !isBytes(c));
}

export function isFile(col: ColumnIR): boolean {
  return col.type.kind === "file";
}

/** File columns of an entity, in model order */
export function fileColumns(entity: EntityIR): ColumnIR[] {
  return entity.columns.filter(isFile);
}

/** Go identifier for a dotted event name: posts.publish becomes PostsPublish, Article.created ArticleCreated */
export function eventIdent(name: string): string {
  return name
    .split(".")
    .map(part => exported(part))
    .join("");
}

export function modulePath(ir: IR): string {
  const slug = ir.name
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, "-")
    .replace(/^[-.]+|[-.]+$/g, "");
  return slug || "app";
}

export function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

/** Go type of the scalar as pgx scans it */
export function scalarGo(scalar: Scalar): string {
  switch (scalar) {
    case "string":
    case "text":
    case "uuid":
    case "decimal":
      return "string";
    case "integer":
      return "int";
    case "bigint":
      return "int64";
    case "float":
      return "float64";
    case "boolean":
      return "bool";
    case "datetime":
    case "date":
      return "time.Time";
    case "time":
      return "pgtype.Time";
    case "json":
      return "json.RawMessage";
    case "bytes":
      return "[]byte";
  }
}

/** Go type of the scalar in the public (JSON) shape */
export function scalarPublicGo(scalar: Scalar): string {
  switch (scalar) {
    case "datetime":
    case "date":
    case "time":
      return "string";
    default:
      return scalarGo(scalar);
  }
}

/** Whether a Go type is a reference type that is nil when the column is NULL */
function isReference(type: string): boolean {
  return type.startsWith("[]") || type === "json.RawMessage";
}

/** Go type of a column in a row struct; file columns hold the stored snapshot (models.FileRef) */
export function rowGoType(col: ColumnIR): string {
  const base = baseGo(col, scalarGo, "FileRef");
  return col.nullable && !isReference(base) ? `*${base}` : base;
}

/** Go type of a column in the public struct; file columns answer models.PublicFile */
export function publicGoType(col: ColumnIR): string {
  const base = baseGo(col, scalarPublicGo, "PublicFile");
  return col.nullable && !isReference(base) ? `*${base}` : base;
}

/** Go type of a validated value of a column (what validation.Type.Parse answers), for action inputs */
export function inputGoType(col: ColumnIR): string {
  const base = baseGo(col, scalarInputGo, "string");
  return col.nullable && !isReference(base) ? `*${base}` : base;
}

/** Go type of the scalar as the validation runtime parses it */
export function scalarInputGo(scalar: Scalar): string {
  switch (scalar) {
    case "date":
    case "time":
      return "string";
    default:
      return scalarGo(scalar);
  }
}

function baseGo(col: ColumnIR, scalar: (s: Scalar) => string, file: string): string {
  const t = col.type;
  if (t.kind === "enum") return "string";
  if (t.kind === "array") return `[]${scalar(t.of)}`;
  if (t.kind === "file") return file;
  return scalar(t.scalar);
}

/** Whether a Go type is a pointer, slice or raw JSON, whose zero value is nil */
export function isNilable(type: string): boolean {
  return type.startsWith("*") || isReference(type);
}

/** The Go zero value of a type, as an expression */
export function zeroValue(type: string): string {
  if (type.startsWith("*") || type === "json.RawMessage") return "nil";
  if (type.startsWith("[]")) return `${type}{}`;
  switch (type) {
    case "string":
      return '""';
    case "int":
    case "int64":
    case "float64":
      return "0";
    case "bool":
      return "false";
    case "time.Time":
      return "time.Time{}";
    case "pgtype.Time":
      return "pgtype.Time{}";
  }
  return `${type}{}`;
}

/** Std imports a Go type needs */
export function importsForType(type: string): string[] {
  const out: string[] = [];
  if (type.includes("time.Time")) out.push("time");
  if (type.includes("pgtype.Time")) out.push("github.com/jackc/pgx/v5/pgtype");
  if (type.includes("json.RawMessage")) out.push("encoding/json");
  return out;
}

/** A gofmt-aligned struct type declaration. Fields without a name are embedded. */
export function goStruct(name: string, fields: { name: string; type: string; tag?: string }[], doc?: string): string {
  const lines: string[] = [];
  if (doc) lines.push(`// ${doc}`);
  lines.push(`type ${name} struct {`);
  // Alignment works on runs of consecutive named fields; an embedded field breaks the run.
  let run: { name: string; type: string; tag?: string }[] = [];
  const flush = () => {
    if (run.length === 0) return;
    const nameWidth = Math.max(...run.map(f => f.name.length));
    const tagged = run.filter(f => f.tag !== undefined);
    const typeWidth = tagged.length ? Math.max(...tagged.map(f => f.type.length)) : 0;
    for (const f of run) {
      if (f.tag === undefined) lines.push(`\t${f.name.padEnd(nameWidth)} ${f.type}`);
      else lines.push(`\t${f.name.padEnd(nameWidth)} ${f.type.padEnd(typeWidth)} ${f.tag}`);
    }
    run = [];
  };
  for (const f of fields) {
    if (f.name === "") {
      flush();
      lines.push(f.tag === undefined ? `\t${f.type}` : `\t${f.type} ${f.tag}`);
    } else run.push(f);
  }
  flush();
  lines.push("}");
  return lines.join("\n");
}

/** An import block with std, third-party and module groups, each sorted. */
export function goImports(modulePath: string, specs: Iterable<string>): string {
  const std: string[] = [];
  const third: string[] = [];
  const own: string[] = [];
  const seen = new Set<string>();
  for (const spec of specs) {
    if (seen.has(spec)) continue;
    seen.add(spec);
    const pathPart = spec.includes(" ") ? spec.slice(spec.indexOf(" ") + 1) : spec;
    if (pathPart === modulePath || pathPart.startsWith(`${modulePath}/`)) own.push(spec);
    else if (pathPart.split("/")[0].includes(".")) third.push(spec);
    else std.push(spec);
  }
  const render = (group: string[]) =>
    group
      .sort((a, b) => importPath(a).localeCompare(importPath(b)))
      .map(spec =>
        spec.includes(" ") ? `\t${spec.slice(0, spec.indexOf(" "))} ${q(importPath(spec))}` : `\t${q(spec)}`
      );
  const groups = [std, third, own].filter(g => g.length).map(render);
  if (groups.length === 0) return "";
  if (groups.length === 1 && groups[0].length === 1) return `import ${groups[0][0].trim()}\n`;
  return `import (\n${groups.map(g => g.join("\n")).join("\n\n")}\n)\n`;
}

function importPath(spec: string): string {
  return spec.includes(" ") ? spec.slice(spec.indexOf(" ") + 1) : spec;
}

export function cap(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function goFile(
  modulePath: string,
  header: string,
  pkg: string,
  imports: Iterable<string>,
  body: string
): string {
  const parts = [header.trimEnd(), `package ${pkg}`];
  const importBlock = goImports(modulePath, imports);
  if (importBlock) parts.push(importBlock.trimEnd());
  if (body.trim()) parts.push(body.trim());
  return parts.join("\n\n") + "\n";
}

/** A gofmt-aligned multi-line keyed literal; falls back to one line when a key is long (gofmt stops aligning). */
export function keyedLiteral(open: string, entries: [string, string][]): string {
  if (entries.length === 0) return `${open}{}`;
  if (entries.some(([key]) => key.length > 40)) return `${open}{${entries.map(([k, v]) => `${k}: ${v}`).join(", ")}}`;
  const width = Math.max(...entries.map(([key]) => key.length)) + 1;
  return `${open}{\n${entries.map(([key, value]) => `\t${(key + ":").padEnd(width)} ${value},`).join("\n")}\n}`;
}

/** The access.Rule literal of a rule; a path becomes its dotted key, which the handler resolves into the Row */
export function ruleLiteral(rule: RuleIR): string {
  const when =
    rule.kind !== "any" && rule.kind !== "all" && rule.kind !== "none" && rule.when
      ? `, When: &access.Condition{Field: ${q(conditionKey(rule.when))}, Op: ${q(rule.when.op)}, Value: ${conditionValue(rule.when.value)}}`
      : "";
  switch (rule.kind) {
    case "owner":
      return `access.Rule{Kind: "owner", Field: ${q(ruleKey(rule))}${when}}`;
    case "role":
      return `access.Rule{Kind: "role", Value: ${q(rule.value)}${when}}`;
    case "member": {
      const through = rule.through
        ? `, Through: true${rule.through.roles ? `, Roles: []string{${rule.through.roles.map(q).join(", ")}}` : ""}`
        : "";
      return rule.role
        ? `access.Rule{Kind: "member", Field: ${q(ruleKey(rule))}, Role: ${q(rule.role)}${through}${when}}`
        : `access.Rule{Kind: "member", Field: ${q(ruleKey(rule))}${through}${when}}`;
    }
    case "all":
      return `access.Rule{Kind: "all", All: []access.Rule{${rule.rules
        .map(r => ruleLiteral(r).replace(/^access\.Rule/, ""))
        .join(", ")}}}`;
    case "any":
      return `access.Rule{Kind: "any", Any: []access.Rule{${rule.rules
        .map(r => ruleLiteral(r).replace(/^access\.Rule/, ""))
        .join(", ")}}}`;
    default:
      return `access.Rule{Kind: ${q(rule.kind)}${when}}`;
  }
}

/** The Go literal of a condition's value, or of a column default */
export function conditionValue(value: string | number | boolean | null): string {
  if (value === null) return "nil";
  if (typeof value === "string") return q(value);
  return String(value);
}

/**
 * The Go type request code holds its database as: the pool, or under isolation: database the scope that runs every
 * statement with the caller's tenants bound (generated/db). Its methods are the pool's, so the code using it is the same.
 */
export function dbType(ir: IR): string {
  return ir.auth?.tenancy?.isolation ? "*db.Scope" : "*pgxpool.Pool";
}

/** The import the database type needs */
export function dbTypeImport(ir: IR, modulePath: string): string {
  return ir.auth?.tenancy?.isolation ? `${modulePath}/generated/db` : "github.com/jackc/pgx/v5/pgxpool";
}
